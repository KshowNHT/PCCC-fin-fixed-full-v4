import './jsdom_setup';
import React, { act } from 'react';
import {createRoot} from 'react-dom/client';
import assert from 'node:assert/strict';
import { BuildingEditor } from '../src/components/BuildingEditor';
import { Sidebar } from '../src/components/Sidebar';
import { MainArea } from '../src/components/MainArea';
import fs from 'node:fs';
async function run(){
 const fixtures=JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'fixtures.json'),'utf8'));
 const root=createRoot(document.getElementById('root')!);
 const updates:any[]=[];
 const base:any={...fixtures.sabaco_multi.project,components:fixtures.sabaco_multi.project.components.map((x:any)=>({basements:0,height:0,pcccHeight:0,floorArea:0,totalFloorArea:0,volume:0,hazardClass:'',industrialSubtype:'',fireRating:'',commercialDetails:'',sourcePages:[],sourceText:'',floors:0,...x}))};
 await act(async()=>root.render(<BuildingEditor project={base} onUpdate={info=>updates.push(info)}/>));
 assert.equal(document.querySelectorAll('article').length,4);
 const grade=document.querySelector('article select') as HTMLSelectElement;
 await act(async()=>{grade.value='D';grade.dispatchEvent(new window.Event('change',{bubbles:true}));});
 assert.equal(updates.length,0,'editing does not trigger review or persist incomplete component');
 await act(async()=>grade.dispatchEvent(new window.FocusEvent('focusout',{bubbles:true,relatedTarget:document.body})));
 assert.equal(updates.length,1);
 assert.equal(updates[0].components.length,4);
 assert.equal(updates[0].components[0].hazardClass,'D');
 assert.equal(updates[0].components[2].volume,98935.2);
 assert.equal(updates[0].componentsComplete,false);
 const sidebarProps:any={project:{type:'Nhà hỗn hợp',floors:77,basements:0,...base},documents:[],sessions:[],activeSessionId:'qa',isPending:false,isSidebarOpen:true,onUpdateProject:()=>{},onUploadDocument:async()=>[],onDeleteDocument:()=>{},onResetDocuments:()=>{},onSelectSession:()=>{},onCreateSession:()=>{},onDeleteSession:()=>{},onTriggerAppraisal:()=>{},setIsSidebarOpen:()=>{}};
 await act(async()=>root.render(<Sidebar {...sidebarProps}/>));
 assert.ok(document.querySelector('#input-type')?.closest('[hidden]'),'single-house inputs are hidden for component mode');
 assert.equal(document.querySelectorAll('article').length,4);
 console.log('PASS U01: component edit saves full inventory on blur, marks confirmation false, preserves other house numbers');
 const fx=fixtures.sabaco_multi;
 const props:any={sessionTitle:'Sabaco',messages:[],onSendMessage:()=>{},onTriggerAppraisal:()=>{},isPending:false,checklist:fx.checklist,isSubjectToAppraisal:fx.isSubject,appraisalReason:fx.reason,appraisalBasis:fx.basis,warnings:fx.warnings,projectInfo:{...base,type:'Nhà hỗn hợp',floors:77,totalFloorArea:777777,pcccHeight:77},onExportReport:()=>{},isExporting:false,onExportReportPdf:()=>{},isExportingPdf:false,isSidebarOpen:false,onToggleSidebar:()=>{},reviewState:'reviewed'};
 await act(async()=>root.render(<MainArea {...props}/>));
 const text=document.body.textContent || '';
 for(const c of base.components)assert.ok(text.includes(c.name));
 assert.ok(text.includes('Dự án nhiều hạng mục'));
 const banner=document.querySelector('#project-specs-banner')?.textContent || '';
 assert.ok(!banner.includes('777777') && !banner.includes('Nhà hỗn hợp'),'old root scale hidden for multi-house project');
 await act(async()=>root.render(<MainArea {...props} reviewState="draft"/>));
 assert.ok(!document.body.textContent?.includes('Kết quả từng hạng mục độc lập'));
 console.log('PASS U02: four reviewed house results render; stale single-house scale hidden; unfinished draft hides component conclusions');
 await act(async()=>root.unmount());
}
run().then(()=>{window.close();process.exit(0);}).catch(e=>{console.error(e);window.close();process.exit(1);});
